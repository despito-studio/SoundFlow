// Build assets for the native installer from the same AnimateIcons renderer as the app.
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:animate_icons/animate_icons.dart';
import 'package:soundflow/installer_design.dart';
import 'package:soundflow/anicry_motion.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  setUpAll(AnimateIcons.load);
  testWidgets('export shared installer icons', (tester) async {
    final output = Directory(
      '${Directory.current.parent.path}/output/installer-icons',
    );
    output.createSync(recursive: true);
    String scalar(double value) => '${value.toStringAsFixed(6)}f';
    String color(Color value) => '0x${value.toARGB32().toRadixString(16)}u';
    String rect(String name, Rect value) =>
        'inline constexpr float ${name}X=${scalar(value.left)}, '
        '${name}Y=${scalar(value.top)}, ${name}Width=${scalar(value.width)}, '
        '${name}Height=${scalar(value.height)};';
    double radius(BorderRadius value) {
      // These controls live inside explicit action groups. Their four corners
      // are equal after the shared concentric rule and Flutter normalization.
      expect(value.topLeft, value.topRight);
      expect(value.topLeft, value.bottomLeft);
      expect(value.topLeft, value.bottomRight);
      return value.topLeft.x;
    }

    String box(Rect value) =>
        '{${scalar(value.left)},${scalar(value.top)},${scalar(value.width)},${scalar(value.height)}}';
    String layout(String name, InstallerLayout value) =>
        'inline constexpr Layout $name={${scalar(value.size.width)},${scalar(value.size.height)},${scalar(value.radius)},'
        '${box(value.logo)},${box(value.title)},${box(value.detail)},${box(value.action)},'
        '${scalar(value.titleSize)},${scalar(value.actionRadius)},${scalar(value.metadata)},${scalar(value.folder)},'
        '${scalar(value.ring)},${scalar(value.check)},${scalar(value.actionOpacity)},${scalar(value.outline)}};';

    final design =
        '''// Generated by export_installer_icons_test.dart. Do not edit.
#pragma once
namespace sf_design {
struct Box {float x,y,width,height;};
struct Layout {float width,height,radius;Box logo,title,detail,action;float titleSize,actionRadius,metadata,folder,ring,check,actionOpacity,outline;};
inline constexpr float viewportWidth=${scalar(InstallerDesign.viewport.width)}, viewportHeight=${scalar(InstallerDesign.viewport.height)};
${layout('readyLayout', InstallerDesign.readyLayout)}
${layout('progressLayout', InstallerDesign.progressLayout)}
${layout('commitLayout', InstallerDesign.commitLayout)}
${layout('completeLayout', InstallerDesign.completeLayout)}
${layout('messageLayout', InstallerDesign.messageLayout)}
inline constexpr float contentScale=${scalar(InstallerDesign.scale)};
inline constexpr int readyWidth=${InstallerDesign.ready.width.toInt()}, readyHeight=${InstallerDesign.ready.height.toInt()};
inline constexpr int compactWidth=${InstallerDesign.compact.width.toInt()}, compactHeight=${InstallerDesign.compact.height.toInt()};
inline constexpr float focusGap=${scalar(InstallerDesign.focusGap)};
inline constexpr float readyRadius=${scalar(InstallerDesign.readyRadius)};
inline constexpr float compactRadius=${scalar(InstallerDesign.compactRadius)};
inline constexpr unsigned background=${color(InstallerDesign.background)};
inline constexpr unsigned ink=${color(InstallerDesign.ink)};
inline constexpr unsigned muted=${color(InstallerDesign.muted)};
inline constexpr unsigned blue=${color(InstallerDesign.blue)};
${rect('download', InstallerDesign.download)}
${rect('folder', InstallerDesign.folder)}
${rect('cancel', InstallerDesign.cancel)}
inline constexpr float downloadRadius=${scalar(radius(InstallerDesign.downloadCorners))};
inline constexpr float folderRadius=${scalar(radius(InstallerDesign.folderCorners))};
inline constexpr float cancelRadius=${scalar(radius(InstallerDesign.cancelCorners))};
inline constexpr float downloadFocusRadius=${scalar(radius(InstallerDesign.focus(InstallerDesign.downloadCorners, InstallerDesign.download.size)))};
inline constexpr float folderFocusRadius=${scalar(radius(InstallerDesign.focus(InstallerDesign.folderCorners, InstallerDesign.folder.size)))};
inline constexpr float cancelFocusRadius=${scalar(radius(InstallerDesign.focus(InstallerDesign.cancelCorners, InstallerDesign.cancel.size)))};
inline constexpr float compactControl=${scalar(InstallerDesign.compactControl)};
inline constexpr float control=${scalar(InstallerDesign.control)};
}
''';
    await tester.runAsync(
      () => File('${output.path}/installer_design.h').writeAsString(design),
    );
    final vectors = StringBuffer(
      '''// Generated from the actual AnimateIcons painter, including its motion.
#pragma once
namespace sf_vectors {
struct Point {float x,y;};
struct Stroke {const Point* points;unsigned count;float width,opacity;bool closed,filled;int cap,join;};
struct Frame {const Stroke* strokes;unsigned count;};
struct Icon {const Frame* frames;unsigned count,duration;};
inline constexpr unsigned layoutMs=${Anicry.layout.inMilliseconds}, revealMs=${Anicry.reveal.inMilliseconds}, pressMs=${Anicry.press.inMilliseconds}, dialogMs=${Anicry.dialog.inMilliseconds};
inline constexpr unsigned contentDelayMs=${Anicry.contentDelay.inMilliseconds}, contentOpacityMs=${Anicry.contentOpacity.inMilliseconds}, contentExitMs=${Anicry.contentExit.inMilliseconds};
inline constexpr float easeOut[]={${List.generate(129, (i) => scalar(Anicry.easeOut.transform(i / 128))).join(',')}};
inline constexpr float easeInOut[]={${List.generate(129, (i) => scalar(Anicry.easeInOut.transform(i / 128))).join(',')}};
''',
    );
    final nativeIcons = <String>[];
    for (final name in [
      'folder-open',
      'download',
      'refresh-cw',
      'x',
      'arrow-left',
      'check',
      'circle-check',
    ]) {
      expect(AnimateIcons.names, contains('lucide/$name'));
      final nativeName = name.replaceAll('-', '_');
      nativeIcons.add(nativeName);
      final duration = AnimateIcons.duration(name).inMilliseconds;
      final animated = [
        'folder-open',
        'refresh-cw',
        'circle-check',
      ].contains(name);
      final count = animated ? (duration * 60 / 1000).ceil() + 1 : 1;
      for (var frame = 0; frame < count; frame++) {
        final strokes = AnimateIcons.vectorFrame(
          name,
          count == 1 ? 1 : frame / (count - 1),
        );
        for (var stroke = 0; stroke < strokes.length; stroke++) {
          vectors.writeln(
            'inline constexpr Point ${nativeName}_${frame}_$stroke[]={${strokes[stroke].points.map((p) => '{${scalar(p.dx)},${scalar(p.dy)}}').join(',')}};',
          );
        }
        if (strokes.isNotEmpty) {
          vectors.writeln('inline constexpr Stroke ${nativeName}_$frame[]={');
          for (var stroke = 0; stroke < strokes.length; stroke++) {
            final s = strokes[stroke];
            vectors.writeln(
              '{${nativeName}_${frame}_$stroke,${s.points.length},${scalar(s.width)},${scalar(s.opacity)},${s.closed},${s.filled},${s.cap.index},${s.join.index}},',
            );
          }
          vectors.writeln('};');
        }
      }
      vectors.writeln('inline constexpr Frame ${nativeName}_frames[]={');
      for (var frame = 0; frame < count; frame++) {
        final strokes = AnimateIcons.vectorFrame(
          name,
          count == 1 ? 1 : frame / (count - 1),
        );
        vectors.writeln(
          strokes.isEmpty
              ? '{nullptr,0},'
              : '{${nativeName}_$frame,${strokes.length}},',
        );
      }
      vectors.writeln(
        '};\ninline constexpr Icon $nativeName={${nativeName}_frames,$count,$duration};',
      );
      final key = GlobalKey();
      await tester.pumpWidget(
        Directionality(
          textDirection: TextDirection.ltr,
          child: Center(
            child: RepaintBoundary(
              key: key,
              child: AnimateIcon(
                name,
                size: 96,
                color: Colors.white,
                animation: const AlwaysStoppedAnimation(1.0),
              ),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();
      await tester.runAsync(() async {
        final boundary =
            key.currentContext!.findRenderObject()! as RenderRepaintBoundary;
        final image = await boundary.toImage();
        final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
        await File('${output.path}/$name.png')
            .writeAsBytes(bytes!.buffer.asUint8List());
        image.dispose();
      });
    }
    vectors.writeln(
      'inline constexpr Icon icons[]={${nativeIcons.join(',')}};\n}',
    );
    await tester.runAsync(
      () =>
          File('${output.path}/installer_vectors.h')
              .writeAsString(vectors.toString()),
    );
  });
}
